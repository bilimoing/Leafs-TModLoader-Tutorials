const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {PGlite}=require('@electric-sql/pglite');
const {createTracker,validate}=require('../tracker');
const {createServer}=require('../server');
const a='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const b='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
test('真实 SQL：初始化、重复请求、延迟重试、在线过期与并发请求',async t=>{
 const db=new PGlite();t.after(()=>db.close());
 for(const file of ['schema.sql','rpc.sql','schema.sql','rpc.sql'])await db.exec(fs.readFileSync(path.join(__dirname,'..',file),'utf8'));
 const track=createTracker(db);
 assert.deepEqual(await track({session:a,event:a,page:'首页'}),{online:1,visits:1,pageVisits:1});
 const retry=await Promise.all([track({session:a,event:a,page:'首页'}),track({session:a,event:a,page:'首页'})]);
 assert.equal(retry[0].visits,1);assert.equal(retry[1].visits,1);
 assert.deepEqual(await track({session:a,event:b,page:'文章'}),{online:1,visits:2,pageVisits:1});
 assert.deepEqual(await track({session:a,event:a,page:'首页'}),{online:1,visits:2,pageVisits:1});
 assert.deepEqual(await track({session:b,event:a,page:'首页'}),{online:2,visits:3,pageVisits:2});
 await db.query('UPDATE public.leaf_stats_sessions SET last_seen=now()-interval \'100 seconds\' WHERE session_id=$1',[a]);
 assert.deepEqual(await track({session:b,event:a,page:'首页'}),{online:1,visits:3,pageVisits:2});
 await db.exec('DELETE FROM public.leaf_stats_totals');
 await assert.rejects(track({session:b,event:b,page:'失败'}),/Missing total counter/);
 const events=await db.query('SELECT count(*) AS n FROM public.leaf_stats_events WHERE session_id=$1 AND event_id=$2',[b,b]);
 assert.equal(Number(events.rows[0].n),0);
});
